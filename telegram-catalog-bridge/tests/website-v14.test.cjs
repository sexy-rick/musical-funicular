const assert = require('node:assert/strict');
const {readFileSync} = require('node:fs');
const {join} = require('node:path');
const {JSDOM} = require('jsdom');
const root = join(__dirname, '../website');
const read = name => readFileSync(join(root, name), 'utf8');
const id = '99eaa0fe-792a-4038-b588-e9ac2f02ce32';
const item = {uuid:id,title:'Example',category:'WORLD'};
(async()=>{
  assert.match(read('index.php'), /href="#catalog">Browse DLCs<\/a><a class="btn hero-app-button" href="\/alium.php">Download app<\/a>/);
  const app = read('alium.php');
  assert.match(app, /https:\/\/github\.com\/Alchemiisst\/Alium\/releases\/download\/v0\.1\.0\/app-release\.apk/);
  assert.match(app, /https:\/\/github\.com\/Alchemiisst\/Alium\/releases/);
  assert.match(app, /Android 7\.0\+/); assert.match(app, /Beta 0\.1\.0/);
  assert.match(read('faq.php'), /select “Download” to open Telegram/);
  assert.match(read('download.php'), /addon\.php\?uuid=/);
  const dom = new JSDOM('<div id="addon-results"></div>',{url:'https://marketplacetrader.great-site.net/addon.php?uuid='+id,runScripts:'outside-only'});
  dom.window.fetch=async()=>({ok:true,json:async()=>({ok:true,item})});
  dom.window.eval(read('assets/catalog-v14.js'));
  await new Promise(r=>setTimeout(r,50));
  const a=dom.window.document.querySelector('.actions a');
  assert.equal(a.textContent,'Download');
  assert.equal(a.getAttribute('href'),'https://t.me/Mc_addonbot?start='+id);
  assert.equal(a.getAttribute('aria-label'),'Download Example in Telegram');
  assert.equal(a.target,'_blank'); assert.match(a.rel,/noopener/);
  assert.equal(dom.window.document.querySelector('.actions a[href^="tg:"]').getAttribute('href'),'tg://resolve?domain=Mc_addonbot&start='+id);
  assert.match(dom.window.document.querySelector('.action-note').textContent,/Telegram/);
  dom.window.close();
  console.log('v14 app page and Telegram detail download passed');
})().catch(e=>{console.error(e);process.exitCode=1});
